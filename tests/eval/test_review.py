"""The operator's gdt review: a worksheet only a human reads, a tally an agent may.

`gdt` has 8 rows wrong in char_type ONLY -- the one bucket where a single-field
fix passes the last-fault test. The GPU-free diagnostics settle half of why:
all 8 were predicted Flatness and all 8 are `parser._gdt_type`'s DEFAULT (no
GD&T symbol recognised in the transcription), so the prediction is a guess on
every row. What they cannot settle is what the drawing actually shows, whether
the symbol is in the transcription in some form the parser does not map, and
whether gold's label names that characteristic. Those need the drawing and
gold's label -- client content, which an agent must never see.

So the work is split along the data boundary:

  * the WORKSHEET carries client text (the label, the transcription, the part
    number) and may only be written inside a protected root, which the agent's
    guard refuses to read. It is generated by `score`, already sanctioned, so
    nothing widens the guard.
  * the TALLY reads the operator's answers -- closed-vocabulary choices only --
    and emits counts. Free-text notes are the operator's own and are never read.

The row set must be exactly the digest's (`report.is_char_type_only`), or the
operator reviews a different set from the one the counts describe.
"""
import json

import pytest

from app.eval.models import (GoldCharacteristic, GoldDoc, MatchParams,
                             PredictionDump, ReviewCostWeights, RunConfig)
from app.eval.review import (WorksheetRefused, build_worksheet, collect_gdt_rows,
                             tally, write_worksheet)
from app.eval.score import score_doc
from app.models import Characteristic, ExtractionResult

SCALE = 300 / 72.0
RECT = (0.0, 0.0, 1191.0, 842.0)
_GDT = dict(kind="gdt", char_type="Flatness", nominal="0", upper_tol="0,05",
            lower_tol="0")


def _box(x, y):
    return (SCALE * (x - 15), SCALE * (y - 5), SCALE * (x + 15), SCALE * (y + 5))


def _doc(doc_id, rows):
    """rows: (x, y, pred_kwargs, gold_kwargs), one matched pair each."""
    gold, preds = [], []
    for i, (x, y, pk, gk) in enumerate(rows):
        gold.append(GoldCharacteristic(balloon=i + 1, position_pt=(x, y), **gk))
        preds.append(Characteristic(pos=i + 1, target_region=_box(x, y), **pk))
    g = GoldDoc(doc_id=doc_id, pdf=f"{doc_id}.pdf", excel=f"{doc_id}.xlsx",
                page_rect=RECT, characteristics=gold)
    d = PredictionDump(doc_id=doc_id, config=RunConfig(model_id="stub", dpi=300),
                       scale=SCALE, page_rect=RECT,
                       result=ExtractionResult(characteristics=preds))
    return d, g


def _collect(*docs):
    dumps, golds, scores = {}, {}, []
    for d, g in docs:
        dumps[d.doc_id], golds[g.doc_id] = d, g
        scores.append(score_doc(d, g, ReviewCostWeights(), MatchParams()))
    return collect_gdt_rows(dumps, golds, scores)


GOLD_POSITION = dict(char_type="Position", nominal="0", upper_tol="0,05",
                     lower_tol="0")


# --- which rows ---------------------------------------------------------------

def test_it_selects_exactly_the_gdt_rows_wrong_in_char_type_only():
    """Same predicate as the digest's `wrong_fields`, so the operator reviews
    the 8 the counts describe -- not the correct row, not the row with a second
    fault a char_type fix cannot free, and not a dimension row."""
    rows = _collect(_doc("P1", [
        (100, 100, dict(_GDT, raw_text="0,05 A"), GOLD_POSITION),
        (300, 100, dict(_GDT, raw_text="0,05 A", upper_tol="9"), GOLD_POSITION),
        (500, 100, dict(_GDT, raw_text="⏥ 0,05"),
         dict(GOLD_POSITION, char_type="Flatness")),
        (700, 100, dict(char_type="Distance", nominal="20", raw_text="20"),
         dict(char_type="Diameter", nominal="20")),
    ]))
    assert [(r.doc_id, r.balloon) for r in rows] == [("P1", 1)]


def test_each_row_carries_the_facts_the_operator_needs():
    rows = _collect(_doc("P1", [
        (100, 100, dict(_GDT, raw_text="0,05 A"), GOLD_POSITION)]))
    r = rows[0]
    assert r.drawing == "P1.pdf" and r.balloon == 1
    assert r.gold_label == "Position" and r.transcription == "0,05 A"
    assert r.predicted == "Flatness"
    assert r.parser_defaulted is True          # no GD&T symbol in "0,05 A"
    assert r.scorer_reads_gold_as == "Position"
    assert r.where == "upper left"


def test_rows_are_grouped_by_drawing_so_each_is_opened_once():
    rows = _collect(
        _doc("P2", [(100, 700, dict(_GDT, raw_text="0,05 A"), GOLD_POSITION)]),
        _doc("P1", [(900, 100, dict(_GDT, raw_text="0,05 A"), GOLD_POSITION),
                    (100, 100, dict(_GDT, raw_text="0,05 B"), GOLD_POSITION)]))
    assert [(r.doc_id, r.balloon) for r in rows] == [("P1", 1), ("P1", 2),
                                                     ("P2", 1)]
    assert [r.where for r in rows] == ["upper right", "upper left", "lower left"]


# --- the worksheet ------------------------------------------------------------

def _rows3():
    return _collect(
        _doc("P1", [(100, 100, dict(_GDT, raw_text="0,05 A"), GOLD_POSITION),
                    (900, 100, dict(_GDT, raw_text="0,1 B"), GOLD_POSITION)]),
        _doc("P2", [(100, 700, dict(_GDT, raw_text="0,02"), GOLD_POSITION)]))


def test_a_blank_worksheet_tallies_as_nothing_answered():
    t = tally(build_worksheet(_rows3()))
    assert t["n_rows"] == 3 and t["answered"] == 0
    assert t["incomplete"] == ["g1", "g2", "g3"]


def _answer(text, rid, drawing, symbol, gold):
    """Fill one row's three answer lines, as the operator would in an editor."""
    head, sep, rest = text.partition(f"## {rid} ")
    assert sep, rid
    block, nxt, tail = rest.partition("\n## ")
    block = (block.replace("drawing_shows:", f"drawing_shows: {drawing}", 1)
                  .replace("symbol_in_transcription:",
                           f"symbol_in_transcription: {symbol}", 1)
                  .replace("gold_label_means_it:",
                           f"gold_label_means_it: {gold}", 1))
    return head + sep + block + nxt + tail


def test_the_tally_routes_each_answered_row_to_where_its_fix_lives():
    """The decision the review exists for. A row is freed WITHOUT A GPU only
    when the prediction side is a parser fix (the symbol IS in the
    transcription, the parser just does not map it) AND the scorer already
    reads gold's label as the same characteristic. A dropped symbol is a read-
    stage fault; a gold label that disagrees with the drawing is a data fault."""
    ws = build_worksheet(_rows3())
    ws = _answer(ws, "g1", "Position", "glyph", "yes")   # parser fix, gold fine
    ws = _answer(ws, "g2", "Position", "none", "yes")    # reader dropped it
    ws = _answer(ws, "g3", "Parallelism", "glyph", "no")  # gold says Position
    t = tally(ws)
    assert t["answered"] == 3 and t["incomplete"] == [] and t["invalid"] == []
    assert t["drawing_shows"] == {"Position": 2, "Parallelism": 1}
    assert t["prediction_fix"] == {"parser": 2, "read_stage": 1}
    assert t["gold_side"] == {"scorer_already_matches": 2,
                              "gold_disagrees_with_drawing": 1}
    assert t["freed_without_gpu"] == 1


def test_a_gold_label_the_scorer_cannot_read_needs_a_synonym_word():
    """5 of the 8 real rows are `unmapped(none)`: the scorer recognises no type
    word in gold's label. If the operator says the label DOES name the
    characteristic, the fix is a synonym-map word -- still CPU-only, so such a
    row is freed without a GPU when the prediction side is a parser fix too."""
    rows = _collect(_doc("P1", [
        (100, 100, dict(_GDT, raw_text="0,05 A"),
         dict(GOLD_POSITION, char_type="Lagetoleranz zu A"))]))
    assert rows[0].scorer_reads_gold_as == "none"
    t = tally(_answer(build_worksheet(rows), "g1", "Position", "word", "yes"))
    assert t["gold_side"] == {"needs_synonym_word": 1}
    assert t["freed_without_gpu"] == 1


def test_answers_are_case_and_spacing_tolerant():
    ws = _answer(build_worksheet(_rows3()), "g1", "total  RUNOUT", "Glyph", "YES")
    t = tally(ws)
    assert t["drawing_shows"] == {"Total runout": 1} and t["invalid"] == []


def test_an_answer_outside_the_vocabulary_is_invalid_not_counted():
    ws = _answer(build_worksheet(_rows3()), "g1", "Positon", "glyph", "yes")
    t = tally(ws)
    assert t["invalid"] == ["g1"] and t["answered"] == 0


def test_the_tally_is_values_blind_whatever_the_operator_writes():
    """The tally output is what reaches an agent, so nothing free-form may pass
    through it: not the operator's notes, not the label or transcription the
    worksheet shows, not the part number."""
    rows = _collect(_doc("PARTNO-4711", [
        (100, 100, dict(_GDT, raw_text="0,05 SECRET-TEXT"),
         dict(GOLD_POSITION, char_type="Position SECRET-LABEL"))]))
    ws = _answer(build_worksheet(rows), "g1", "Position", "glyph", "yes")
    ws = ws.replace("note:", "note: SECRET-NOTE", 1)
    blob = json.dumps(tally(ws), ensure_ascii=False)
    for leak in ("SECRET", "PARTNO", "4711", "0,05"):
        assert leak not in blob, leak


# --- where it may be written --------------------------------------------------

def _roots(tmp_path, monkeypatch, *roots):
    f = tmp_path / "protected-paths"
    f.write_text("".join(f"{r}\n" for r in roots))
    monkeypatch.setenv("SINDRI_PROTECTED_PATHS", str(f))


def test_the_worksheet_is_written_only_inside_a_protected_root(tmp_path,
                                                               monkeypatch):
    """It holds client text. Inside a protected root the agent's guard refuses
    to read it; anywhere else -- docs/, the scratchpad -- an agent could."""
    root = tmp_path / "client"
    root.mkdir()
    _roots(tmp_path, monkeypatch, root)
    with pytest.raises(WorksheetRefused, match="protected root"):
        write_worksheet(tmp_path / "outside.md", _rows3())
    write_worksheet(root / "reports" / "gdt-review.md", _rows3())
    assert (root / "reports" / "gdt-review.md").exists()


def test_it_refuses_when_no_protected_roots_are_configured(tmp_path, monkeypatch):
    """No roots file means nowhere is known to be safe -- refuse, never guess."""
    monkeypatch.setenv("SINDRI_PROTECTED_PATHS", str(tmp_path / "missing"))
    with pytest.raises(WorksheetRefused):
        write_worksheet(tmp_path / "x.md", _rows3())


def test_a_path_that_only_LOOKS_inside_a_root_is_refused(tmp_path, monkeypatch):
    """`<root>/../elsewhere` and `<root>-copy` start with the root's text and
    are outside it."""
    root = tmp_path / "client"
    root.mkdir()
    _roots(tmp_path, monkeypatch, root)
    for bad in (root / ".." / "elsewhere.md", tmp_path / "client-copy" / "x.md"):
        with pytest.raises(WorksheetRefused):
            write_worksheet(bad, _rows3())


def test_it_never_overwrites_a_worksheet_the_operator_may_have_filled(
        tmp_path, monkeypatch):
    """Re-running `score` must not erase ten minutes of someone's answers."""
    root = tmp_path / "client"
    root.mkdir()
    _roots(tmp_path, monkeypatch, root)
    path = root / "gdt-review.md"
    write_worksheet(path, _rows3())
    with pytest.raises(WorksheetRefused, match="exists"):
        write_worksheet(path, _rows3())


def test_the_introduction_counts_the_guesses_rather_than_asserting_them():
    """On today's run all 8 types are the parser's default, but the worksheet
    is regenerated from whatever run it is given, and its prose must not claim
    what that run does not show."""
    rows = _collect(_doc("P1", [
        (100, 100, dict(_GDT, raw_text="0,05 A"), GOLD_POSITION),
        (900, 100, dict(_GDT, char_type="Parallelism", raw_text="∥ 0,05 A"),
         GOLD_POSITION)]))
    ws = build_worksheet(rows)
    assert "1 of 2" in ws.split("## How to do it")[0]


# --- the two entry points -----------------------------------------------------

from app.eval.runner import main  # noqa: E402
from tests.eval.test_score_scope_policy import _corpus  # noqa: E402


def _score_args(tmp_path, run_dir, gold_dir, worksheet):
    return ["score", "--run", str(run_dir), "--gold", str(gold_dir),
            "--name", "ws", "--out", str(tmp_path / "scored.json"),
            "--gdt-worksheet", str(worksheet)]


def test_score_refuses_a_worksheet_outside_a_protected_root_BEFORE_scoring(
        tmp_path, monkeypatch):
    """Fail in seconds, not after a full re-score, and write no report either:
    a refusal that still did the work would teach the operator to ignore it."""
    _roots(tmp_path, monkeypatch, tmp_path / "client")
    pdfs, gold_dir, run_dir = _corpus(tmp_path)
    rc = main(_score_args(tmp_path, run_dir, gold_dir, tmp_path / "ws.md"))
    assert rc == 1
    assert not (tmp_path / "ws.md").exists()
    assert not (tmp_path / "scored.json").exists()


def test_score_writes_the_worksheet_and_prints_only_a_count(tmp_path, monkeypatch,
                                                            capsys):
    root = tmp_path / "client"
    root.mkdir()
    _roots(tmp_path, monkeypatch, root)
    pdfs, gold_dir, run_dir = _corpus(tmp_path)
    ws = root / "reports" / "gdt-review.md"
    assert main(_score_args(tmp_path, run_dir, gold_dir, ws)) == 0
    assert ws.exists()
    printed = capsys.readouterr()
    assert "gdt review worksheet:" in printed.out
    assert "sindri-gdt-review" not in printed.out + printed.err


def test_review_tally_writes_counts_to_out(tmp_path):
    ws = tmp_path / "ws.md"
    ws.write_text(_answer(build_worksheet(_rows3()), "g1", "Position", "glyph",
                          "yes"), encoding="utf-8")
    out = tmp_path / "tally.json"
    assert main(["review-tally", str(ws), "--out", str(out)]) == 0
    t = json.loads(out.read_text())
    assert t["answered"] == 1 and t["freed_without_gpu"] == 1
